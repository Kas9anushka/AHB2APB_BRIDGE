`default_nettype none

module RESPONSE_ERROR_MAPPER #(
    parameter DATA_WIDTH = 32
)(
    input  wire                    HCLK,
    input  wire                    HRESETn,
    // response input from request cdc
    input  wire                    rsp_valid, // pulse generated by REQUEST_CDC
    input  wire [DATA_WIDTH-1:0]   rsp_rdata, // read data return from APB side
    input  wire                    rsp_err,
    // ahb response outputs
    output reg  [DATA_WIDTH-1:0]   HRDATA, // read data return to ahb master
    output reg                     HRESP, // high represent an error
    output reg                     resp_done   // qualifies HREADYOUT in ahb_capture
);

localparam RESP_IDLE = 1'b0; // waiting for a response from REQUEST_CDC
localparam RESP_ERR2 = 1'b1; // 2nd cycle of an AHB ERROR response

reg state, nextstate;    
// next value of the fsm state response
reg [DATA_WIDTH-1:0] HRDATA_next;
reg               HRESP_next;
reg               resp_done_next;

// determine how response should be generated based on rsp_valid and rsp_err
always @(*) begin
	nextstate     = state;
	HRDATA_next    = HRDATA;
	HRESP_next     = HRESP;
	resp_done_next = 1'b0;
   // wait for valid response has arrived to HCLK domain
		case (state)
    	RESP_IDLE: begin
        // capture the read data
      	if (rsp_valid) begin
        	HRDATA_next = rsp_rdata;
          
          if (rsp_err) begin
          	HRESP_next     = 1'b1;   
            resp_done_next = 1'b0;
            nextstate     = RESP_ERR2;
          end else begin
          	HRESP_next     = 1'b0;  
            resp_done_next = 1'b1;
           	nextstate     = RESP_IDLE;
          end
        end
      end
			RESP_ERR2: begin
      	HRESP_next     = 1'b1; //Keep HRESP asserted to indicate ERROR.  
        resp_done_next = 1'b1; // The complete error response is now finished.
        nextstate     = RESP_IDLE;
      end
			default: nextstate = RESP_IDLE;
		endcase
end

always @(posedge HCLK or negedge HRESETn) begin
	if (!HRESETn) begin
  	state     <= RESP_IDLE;
    HRDATA    <= {DATA_WIDTH{1'b0}};
    HRESP     <= 1'b0;
    resp_done <= 1'b0;
  end else begin
  	state     <= nextstate;
    HRDATA    <= HRDATA_next;  // Update AHB response data.
    HRESP     <= HRESP_next;  // Update AHB response status.
    resp_done <= resp_done_next; // Update response completion indication.
  end
end
endmodule
